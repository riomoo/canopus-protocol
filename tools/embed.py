#!/usr/bin/env python3
"""Turns files into C headers (byte arrays) for the runtime and launcher.

    tools/embed.py out.h NAME=path [NAME=path ...]

The headers are committed; run this again when the pictures or the font
change:
    tools/embed.py runtime/res/backdrop_png.h \
        kBackdropLogoPng=branding/backdrop/canopus-protocol-backdrop-logo-1920x1080.png \
        kBackdropPng=branding/backdrop/canopus-protocol-backdrop-1920x1080.png
    tools/embed.py launcher/res/font_ttf.h kFontTtf=launcher/res/inter-semibold.ttf
"""
import os
import sys

out, items = sys.argv[1], sys.argv[2:]
with open(out, "w", newline="\n") as f:
    f.write("// Generated by tools/embed.py: do not edit.\n#pragma once\n\n")
    for item in items:
        name, path = item.split("=", 1)
        data = open(path, "rb").read()
        f.write(f"// {os.path.basename(path)}\nstatic const unsigned char {name}[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("};\n\n")
